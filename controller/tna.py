from pathlib import Path

VERSION = "0.1.0"
DEFAULT_REPO = "Shitsuki4/tailnet-assist"
DEFAULT_REF = "v" + VERSION
INFO_PREFIX = "TNA1:"
HOST_PREFIX = "tna-"

NAME_RE = re.compile(r"^[a-z0-9][a-z0-9-]{0,39}$")
USER_RE = re.compile(r"^[A-Za-z0-9._@\\-][A-Za-z0-9._@\\ -]{0,63}$")
HOST_RE = re.compile(r"^(?=.{1,253}$)[A-Za-z0-9](?:[A-Za-z0-9.:-]*[A-Za-z0-9])?$")
HOSTKEY_RE = re.compile(
    r"^(ssh-ed25519|ecdsa-sha2-nistp256|ecdsa-sha2-nistp384|ecdsa-sha2-nistp521|ssh-rsa) [A-Za-z0-9+/]+={0,3}$"
)
EXPIRES_RE = re.compile(r"^(never|\d{1,3}[hd])$")
OS_CHOICES = ("windows", "macos", "linux")
SHELL_CHOICES = ("cmd", "powershell", "sh")
BAD_PATH_CHARS = set('"\'\r\n\t`$%;&|<>^')


class TnaError(Exception):
    pass


# ---------------------------------------------------------------- paths

def home_dir() -> Path:
    env = os.environ.get("TNA_HOME")
    return Path(env) if env else Path.home() / ".tailnet-assist"


def repo_root() -> Path:
    return Path(__file__).resolve().parent.parent


def target_script(os_name: str) -> Path:
    if os_name == "windows":
        return repo_root() / "target" / "windows" / "tna-target.ps1"
    return repo_root() / "target" / "unix" / "tna-target.sh"


def key_path() -> Path:
    return home_dir() / "id_ed25519"


def targets_path() -> Path:
    return home_dir() / "targets.json"


def ssh_config_path() -> Path:
    return home_dir() / "ssh_config"


def known_hosts_path() -> Path:
    return home_dir() / "known_hosts"


# ---------------------------------------------------------------- helpers

def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def key_fingerprint(pubkey_line: str) -> str:
    """OpenSSH style SHA256 fingerprint of a public key line."""
    parts = pubkey_line.split()
    if len(parts) < 2:
        raise TnaError("不是有效的公钥行")
    blob = base64.b64decode(parts[1])
    return "SHA256:" + base64.b64encode(hashlib.sha256(blob).digest()).decode().rstrip("=")


def pubkey_blob_ok(line: str) -> bool:
    """The base64 blob must start with the same key type, length-prefixed."""
    try:
        ktype, b64 = line.split(" ")[:2]
        blob = base64.b64decode(b64, validate=True)
    except Exception:  # noqa: BLE001
        return False
    n = int.from_bytes(blob[:4], "big")
    return n == len(ktype) and blob[4:4 + n].decode("ascii", "replace") == ktype


def read_pubkey() -> str:
    pub = key_path().with_suffix(".pub")
    if not pub.exists():
        raise TnaError("还没有控制端密钥，先运行: tna init")
    return pub.read_text(encoding="utf-8").strip()


def ps_single_quote(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def load_targets() -> dict:
    p = targets_path()
    if not p.exists():
        return {}
    return json.loads(p.read_text(encoding="utf-8"))


def save_targets(targets: dict) -> None:
    home_dir().mkdir(parents=True, exist_ok=True)
    tmp = targets_path().with_suffix(".tmp")
    tmp.write_text(json.dumps(targets, ensure_ascii=False, indent=2, sort_keys=True), encoding="utf-8")
    os.replace(tmp, targets_path())
    write_ssh_files(targets)


def q(path: Path) -> str:
    return '"' + str(path).replace("\\", "/") + '"'


def write_ssh_files(targets: dict) -> None:
    lines = [
        "# Generated by tailnet-assist (tna). Edits are overwritten.",
        "# Used with: ssh -F <this file> tna-<name>",
        "",
    ]
    kh = []
    for name in sorted(targets):
        t = targets[name]
        alias = HOST_PREFIX + name
        lines += [
            f"Host {alias}",
            f"    HostName {t['host']}",
            f"    User {t['user']}" if " " not in t["user"] else f"    User \"{t['user']}\"",
            f"    Port {int(t.get('port', 22))}",
            f"    IdentityFile {q(key_path())}",
            "    IdentitiesOnly yes",
            f"    UserKnownHostsFile {q(known_hosts_path())}",
            f"    HostKeyAlias {alias}",
            "    StrictHostKeyChecking yes",
            "    BatchMode yes",
            "    PasswordAuthentication no",
            "    ConnectTimeout 20",
            "    ServerAliveInterval 15",
            "    ServerAliveCountMax 4",
            "    ForwardAgent no",
            "    ForwardX11 no",
            "    ClearAllForwardings yes",
            "",
        ]
        kh.append(f"{alias} {t['hostkey']}")
    home_dir().mkdir(parents=True, exist_ok=True)
    ssh_config_path().write_text("\n".join(lines), encoding="utf-8")
    known_hosts_path().write_text("\n".join(kh) + ("\n" if kh else ""), encoding="utf-8")


# ---------------------------------------------------------------- connection info

def encode_info(info: dict) -> str:
    raw = json.dumps(info, separators=(",", ":"), ensure_ascii=False).encode()
    return INFO_PREFIX + base64.urlsafe_b64encode(raw).decode().rstrip("=")


def decode_info(line: str) -> dict:
    line = line.strip()
    if not line.startswith(INFO_PREFIX):
        raise TnaError("连接信息应以 TNA1: 开头")
    body = line[len(INFO_PREFIX):]
    body += "=" * (-len(body) % 4)
    try:
        info = json.loads(base64.urlsafe_b64decode(body.encode()).decode())
    except Exception as e:  # noqa: BLE001
        raise TnaError(f"连接信息无法解析: {e}") from e
    return validate_info(info)


def _check_path(p, os_name: str) -> str:
    if not isinstance(p, str) or not p or len(p) > 400:
        raise TnaError("cua 路径无效")
    if os_name == "windows":
        if any(c in BAD_PATH_CHARS for c in p) or not re.match(r"^[A-Za-z]:\\", p):
            raise TnaError(f"Windows 路径含不允许的字符: {p!r}")
    else:
        if any(c in "\r\n\t\0" for c in p) or not p.startswith("/"):
            raise TnaError(f"路径无效: {p!r}")
    return p


def validate_info(info: dict) -> dict:
    if not isinstance(info, dict) or info.get("v") != 1:
        raise TnaError("连接信息版本不支持")
    out = {"v": 1}
    name = str(info.get("name", "")).lower()
    name = re.sub(r"[^a-z0-9-]+", "-", name).strip("-")[:40] or "target"
    if not NAME_RE.match(name):
        raise TnaError("名称无效")
    out["name"] = name
    os_name = info.get("os")
    if os_name not in OS_CHOICES:
        raise TnaError("os 字段无效")
    out["os"] = os_name
    user = info.get("user")
    if not isinstance(user, str) or not USER_RE.match(user):
        raise TnaError("用户名无效")
    out["user"] = user
    host = info.get("host") or info.get("ip")
    if not isinstance(host, str) or not HOST_RE.match(host.rstrip(".")):
        raise TnaError("主机地址无效")
    out["host"] = host.rstrip(".")
    ip = info.get("ip")
    if ip is not None:
        if not isinstance(ip, str) or not re.match(r"^[0-9a-fA-F:.]{2,45}$", ip):
            raise TnaError("IP 无效")
        out["ip"] = ip
    hostkey = info.get("hostkey")
    if not isinstance(hostkey, str):
        raise TnaError("缺少主机公钥")
    if re.search(r"[\x00-\x1f]", hostkey):
        raise TnaError("主机公钥含控制字符")
    parts = hostkey.strip().split(" ")
    hostkey = " ".join(parts[:2])
    if len(parts) > 3 or not HOSTKEY_RE.match(hostkey) or not pubkey_blob_ok(hostkey):
        raise TnaError("主机公钥格式无效")
    out["hostkey"] = hostkey
    shell = info.get("shell") or ("cmd" if os_name == "windows" else "sh")
    if shell not in SHELL_CHOICES:
        raise TnaError("shell 字段无效")
    out["shell"] = shell
    out["cua"] = _check_path(info.get("cua"), os_name) if info.get("cua") else None
    sock = info.get("socket")
    if sock is not None:
        if os_name == "windows":
            if not re.match(r"^\\\\\.\\pipe\\[A-Za-z0-9._-]{1,64}$", sock):
                raise TnaError("命名管道无效")
        else:
            _check_path(sock, os_name)
        out["socket"] = sock
    else:
        out["socket"] = None
    port = info.get("port", 22)
    if not isinstance(port, int) or not 1 <= port <= 65535:
        raise TnaError("端口无效")
    if port != 22:
        out["port"] = port
    for k in ("expires", "created", "keyid"):
        v = info.get(k)
        if v is not None:
            if not isinstance(v, str) or len(v) > 40 or not re.match(r"^[0-9A-Za-z:._+-]*$", v):
                raise TnaError(f"{k} 字段无效")
            out[k] = v
    return out


# ---------------------------------------------------------------- command builders

def remote_mcp_command(t: dict) -> str:
    """The command string the target's login shell runs to start the MCP stdio server."""
    if not t.get("cua"):
        raise TnaError("目标端没有报告 Cua Driver 路径（安装时可能用了 -SkipCua/--skip-cua）")
    if t["os"] == "windows":
        exe = t["cua"]
        sock = t.get("socket") or r"\\.\pipe\cua-driver"
        if t.get("shell") == "powershell":
            return f"& {ps_single_quote(exe)} mcp --socket {ps_single_quote(sock)}"
        folder, _, base = exe.rpartition("\\")
        # Begin with a non-quote character so cmd.exe never strips our quotes.
        return f'cd /d "{folder}" && {base} mcp --socket {sock}'
    cmd = shlex.quote(t["cua"]) + " mcp"
    if t["os"] == "linux":
        sock = t.get("socket")
        cmd += " --socket " + (shlex.quote(sock) if sock else "~/.cache/cua-driver/cua-driver.sock")
    return cmd


def ssh_base(name: str) -> list:
    return ["ssh", "-F", str(ssh_config_path()), "-T", HOST_PREFIX + name]


def mcp_launch_argv(name: str, t: dict) -> list:
    return ssh_base(name) + [remote_mcp_command(t)]


def toml_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def codex_toml(name: str, t: dict) -> str:
    argv = mcp_launch_argv(name, t)
    args = ", ".join(toml_str(a) for a in argv[1:])
    return (
        f"[mcp_servers.{toml_key(name)}]\n"
        f"command = {toml_str(argv[0])}\n"
        f"args = [{args}]\n"
        "startup_timeout_sec = 45\n"
        "tool_timeout_sec = 120\n"
    )


def toml_key(name: str) -> str:
    return "cua-" + name if re.match(r"^[A-Za-z0-9_-]+$", name) else toml_str("cua-" + name)


def codex_cli(name: str, t: dict) -> list:
    return ["codex", "mcp", "add", "cua-" + name, "--"] + mcp_launch_argv(name, t)


def shell_join(argv: list) -> str:
    if os.name == "nt":
        return subprocess.list2cmdline(argv)
    return " ".join(shlex.quote(a) for a in argv)


def invite_command(os_name: str, pubkey: str, expires: str, label: str, repo: str, ref: str,
                   script_hash: str) -> str:
    path = "target/windows/tna-target.ps1" if os_name == "windows" else "target/unix/tna-target.sh"
    url = f"https://raw.githubusercontent.com/{repo}/{ref}/{path}"
    if os_name == "windows":
        return (
            "$ErrorActionPreference='Stop';"
            f"$u={ps_single_quote(url)};$f=Join-Path $env:TEMP 'tna-target.ps1';"
            "Invoke-WebRequest -UseBasicParsing $u -OutFile $f;"
            f"if((Get-FileHash $f -Algorithm SHA256).Hash -ne {ps_single_quote(script_hash.upper())})"
            "{throw 'SHA256 mismatch: script changed, do not run it'};"
            "powershell -NoProfile -ExecutionPolicy Bypass -File $f setup"
            f" -OperatorKey {ps_single_quote(pubkey)} -Expires {expires} -Label {ps_single_quote(label)}"
        )
    return (
        f"f=$(mktemp) && curl -fsSL {shlex.quote(url)} -o \"$f\" && "
        f"echo '{script_hash}  '\"$f\" | (sha256sum -c - 2>/dev/null || shasum -a 256 -c -) && "
        f"bash \"$f\" setup --operator-key {shlex.quote(pubkey)} --expires {expires} --label {shlex.quote(label)}"
    )


# ---------------------------------------------------------------- MCP stdio client

class McpClient:
    def __init__(self, argv: list, timeout: float = 60.0):
        self.timeout = timeout
        self.proc = subprocess.Popen(argv, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                                     stderr=subprocess.PIPE, bufsize=0)
        self._q: "queue.Queue" = queue.Queue()
        self._next = 1
        self.stderr_lines: list = []
        threading.Thread(target=self._reader, daemon=True).start()
        threading.Thread(target=self._err_reader, daemon=True).start()

    def _reader(self):
        assert self.proc.stdout
        for raw in self.proc.stdout:
            line = raw.decode("utf-8", "replace").strip()
            if not line:
                continue
            try:
                self._q.put(json.loads(line))
            except ValueError:
                self.stderr_lines.append("[stdout] " + line[:300])
        self._q.put(None)

    def _err_reader(self):
        assert self.proc.stderr
        for raw in self.proc.stderr:
            self.stderr_lines.append(raw.decode("utf-8", "replace").rstrip()[:500])

    def _send(self, obj: dict):
        assert self.proc.stdin
        self.proc.stdin.write((json.dumps(obj) + "\n").encode())
        self.proc.stdin.flush()

    def request(self, method: str, params=None) -> dict:
        rid = self._next
        self._next += 1
        msg = {"jsonrpc": "2.0", "id": rid, "method": method}
        if params is not None:
            msg["params"] = params
        self._send(msg)
        while True:
            try:
                resp = self._q.get(timeout=self.timeout)
            except queue.Empty:
                raise TnaError(f"MCP 请求 {method} 超时；stderr: {' | '.join(self.stderr_lines[-5:])}") from None
            if resp is None:
                raise TnaError(f"MCP 进程已退出；stderr: {' | '.join(self.stderr_lines[-8:])}")
            if resp.get("id") == rid:
                if "error" in resp:
                    raise TnaError(f"MCP {method} 出错: {resp['error']}")
                return resp.get("result", {})

    def notify(self, method: str, params=None):
        msg = {"jsonrpc": "2.0", "method": method}
        if params is not None:
            msg["params"] = params
        self._send(msg)

    def initialize(self) -> dict:
        res = self.request("initialize", {
            "protocolVersion": "2025-06-18",
            "capabilities": {},
            "clientInfo": {"name": "tailnet-assist-probe", "version": VERSION},
        })
        self.notify("notifications/initialized")
        return res

    def call(self, tool: str, args: dict) -> dict:
        return self.request("tools/call", {"name": tool, "arguments": args})

    def close(self):
        try:
            if self.proc.stdin:
                self.proc.stdin.close()
            self.proc.wait(timeout=10)
        except Exception:  # noqa: BLE001
            self.proc.kill()


def text_of(result: dict) -> str:
    return "\n".join(c.get("text", "") for c in result.get("content", []) if c.get("type") == "text")


# ---------------------------------------------------------------- commands

def cmd_init(a):
    home_dir().mkdir(parents=True, exist_ok=True)
    if key_path().exists() and not a.force:
        print(f"已有控制端密钥: {key_path()}")
    else:
        if not shutil.which("ssh-keygen"):
            raise TnaError("找不到 ssh-keygen，请先安装 OpenSSH 客户端")
        for p in (key_path(), key_path().with_suffix(".pub")):
            if p.exists():
                p.unlink()
        comment = f"tna-operator:{getpass.getuser()}@{socket.gethostname()}"
        comment = re.sub(r"[^A-Za-z0-9@._:-]", "_", comment)
        subprocess.run(["ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-C", comment,
                        "-f", str(key_path())], check=True)
        print(f"已生成专用密钥: {key_path()}")
    pub = read_pubkey()
    print(f"公钥指纹: {key_fingerprint(pub)}")
    if not targets_path().exists():
        save_targets({})


def cmd_invite(a):
    pub = read_pubkey()
    if not EXPIRES_RE.match(a.expires):
        raise TnaError("--expires 只接受 never、数字+h、数字+d，例如 8h、7d")
    label = re.sub(r"[^A-Za-z0-9._-]", "-", a.label or f"{getpass.getuser()}-{socket.gethostname()}")[:40]
    script = target_script(a.os)
    h = a.sha256 or sha256_file(script)
    print(f"# 发给 {a.os} 机器的主人，在桌面会话里运行" + ("（PowerShell）" if a.os == "windows" else "（终端）") + "：")
    print(invite_command(a.os, pub, a.expires, label, a.repo, a.ref, h))
    print()
    print(f"# 控制端公钥指纹 {key_fingerprint(pub)}，对方的安装窗口会显示同一个指纹，请对方核对。")
    print(f"# 脚本版本 {a.ref}，SHA256 {h}（取自本地 {script.relative_to(repo_root())}，须与该版本一致）。")


def cmd_add(a):
    info = decode_info(a.info)
    name = a.name or info["name"]
    if not NAME_RE.match(name):
        raise TnaError("名称只能用小写字母、数字和连字符")
    targets = load_targets()
    if name in targets and not a.force:
        raise TnaError(f"{name} 已存在，用 --force 覆盖或 --name 换个名字")
    info["name"] = name
    info["added"] = _dt.datetime.now(_dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    targets[name] = info
    save_targets(targets)
    print(f"已添加 {name}: {info['user']}@{info['host']} ({info['os']})")
    print(f"主机公钥指纹 {key_fingerprint(info['hostkey'])}（已固定，变了会拒绝连接）")
    if info.get("expires"):
        print(f"对方设置的授权到期时间: {info['expires']}")
    print(f"下一步: python3 {Path(__file__).name} doctor {name}")


def cmd_list(a):
    targets = load_targets()
    if not targets:
        print("还没有目标机。")
        return
    for name, t in sorted(targets.items()):
        print(f"{name:20} {t['os']:8} {t['user']}@{t['host']}  到期: {t.get('expires') or '未设置'}")


def get_target(name: str) -> dict:
    t = load_targets().get(name)
    if not t:
        raise TnaError(f"没有名为 {name} 的目标机（tna list 查看）")
    return t


def cmd_remove(a):
    targets = load_targets()
    if targets.pop(a.name, None) is None:
        raise TnaError(f"没有名为 {a.name} 的目标机")
    save_targets(targets)
    print(f"已从本机删除 {a.name}。这只删了控制端记录；要让对方机器也撤销授权，请对方运行 revoke。")
    if shutil.which("codex"):
        print(f"如果之前加过 Codex 配置: codex mcp remove cua-{a.name}")


def cmd_ssh(a):
    get_target(a.name)
    sys.stdout.flush()
    argv = ssh_base(a.name)
    if a.command:
        cmd = a.command[1:] if a.command[0] == "--" else a.command
        argv += [" ".join(cmd)]
    else:
        argv = [x for x in argv if x != "-T"]
    sys.exit(subprocess.call(argv))


def cmd_mcp_config(a):
    t = get_target(a.name)
    if a.format == "toml":
        print(codex_toml(a.name, t), end="")
    elif a.format == "json":
        argv = mcp_launch_argv(a.name, t)
        print(json.dumps({"mcpServers": {"cua-" + a.name: {"command": argv[0], "args": argv[1:]}}},
                         ensure_ascii=False, indent=2))
    else:
        print(shell_join(codex_cli(a.name, t)))


def cmd_codex_add(a):
    t = get_target(a.name)
    if not shutil.which("codex"):
        raise TnaError("找不到 codex 命令。可以用 tna mcp-config --format toml 手动写入 ~/.codex/config.toml")
    argv = codex_cli(a.name, t)
    print("+ " + shell_join(argv))
    subprocess.run(argv, check=True)
    print("已写入 Codex 配置。建议再把 startup_timeout_sec 调大（见 tna mcp-config --format toml）。")


def cmd_doctor(a):
    t = get_target(a.name)
    ok = True
    print(f"[1/3] SSH 登录 {t['user']}@{t['host']} ...")
    r = subprocess.run(ssh_base(a.name) + ["echo tna-ok"], capture_output=True, text=True,
                       encoding="utf-8", errors="replace", timeout=60)
    if r.returncode == 0 and "tna-ok" in r.stdout:
        print("      通过")
    else:
        ok = False
        print(f"      失败 (exit {r.returncode}): {r.stderr.strip()[-400:]}")
        print("      检查: 两边 tailscale status 是否在线、访问规则是否允许 tcp:22、对方是否已 revoke/到期。")
        sys.exit(1)
    print("[2/3] MCP 握手（通过 SSH 启动 cua-driver mcp）...")
    try:
        probe(a.name, t, screenshot=a.screenshot, verbose=True)
        print("[3/3] 完成")
    except TnaError as e:
        ok = False
        print(f"      失败: {e}")
        print("      检查: 对方桌面是否已登录未锁屏、cua-driver 守护进程是否在运行（目标端 status）。")
    sys.exit(0 if ok else 1)


def probe(name: str, t: dict, screenshot: str | None = None, verbose: bool = False) -> dict:
    c = McpClient(mcp_launch_argv(name, t))
    try:
        init = c.initialize()
        server = init.get("serverInfo", {})
        tools = c.request("tools/list").get("tools", [])
        names = sorted(x.get("name") for x in tools)
        size = c.call("get_screen_size", {})
        report = {"server": server, "tool_count": len(names), "screen": text_of(size)[:300]}
        if verbose:
            print(f"      服务端 {server.get('name')} {server.get('version')}，{len(names)} 个工具")
            for need in ("get_desktop_state", "click", "type_text", "hotkey"):
                print(f"      {'有' if need in names else '缺'} {need}")
            print(f"      屏幕: {report['screen']}")
        if screenshot:
            res = c.call("get_desktop_state", {"max_image_dimension": 1600})
            imgs = [x for x in res.get("content", []) if x.get("type") == "image"]
            if not imgs:
                raise TnaError("截图没有返回图片: " + text_of(res)[:300])
            Path(screenshot).write_bytes(base64.b64decode(imgs[0]["data"]))
            report["screenshot"] = screenshot
            if verbose:
                print(f"      截图已保存: {screenshot}")
        return report
    finally:
        c.close()


