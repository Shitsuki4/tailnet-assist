#!/usr/bin/env python3
"""tailnet-assist controller (tna).

Runs on the operator machine (the machine where an external Codex runs).
It only manages local files under ~/.tailnet-assist and calls the system
`ssh` / `ssh-keygen` / `codex` binaries. It never embeds or bundles Codex.

Python 3.8+, standard library only. Works on Windows, macOS and Linux.
"""
from __future__ import annotations

import argparse
import base64
import datetime as _dt
import getpass
import hashlib
import json
import os
import queue
import re
import shlex
import shutil
import socket
import subprocess
import sys
